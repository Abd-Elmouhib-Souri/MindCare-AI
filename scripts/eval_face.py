"""
Face emotion model - honest evaluation on the OFFICIAL FER-2013 test split.

The original training never used the test split (validation came from train), so the
existing model can be evaluated without retraining. Before scoring, we audit the split:
  - images per class (FER-2013 is imbalanced: 'disgust' is rare -> macro-F1 matters)
  - exact pixel duplicates between train and test (a face seen in training = leakage)
Then we report: accuracy and macro-F1 with 95 % bootstrap CIs, per-class P/R/F1,
confusion matrix, top-label calibration (ECE), and the same metrics on the test set
WITHOUT the cross-split duplicates (sensitivity analysis).

Usage (repo root, .venv active):
  python scripts/eval_face.py --fer-dir ..\\mindcare_data\\dataset\\images --model <best_vision_stage2.keras>
"""

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from mindcare.face import list_split, load_face_model, load_image, pixel_hash  # noqa: E402
from mindcare.multiclass import (EMOTIONS, markdown_table, multiclass_bootstrap,  # noqa: E402
                                 multiclass_metrics, per_class_table, top_label_ece)


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--fer-dir", required=True, help="folder that contains train/ and test/")
    p.add_argument("--model", required=True)
    p.add_argument("--out", default="eval/results")
    args = p.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    train = list_split(str(Path(args.fer_dir) / "train"))
    test = list_split(str(Path(args.fer_dir) / "test"))
    print(f"train {len(train):,} | test {len(test):,}")

    # ---- Audit: class counts and cross-split duplicates ----------------------------------
    counts = {s: {EMOTIONS[k]: v for k, v in sorted(Counter(l for _, l in items).items())}
              for s, items in (("train", train), ("test", test))}
    print("Hashing pixels to find duplicates (1-2 min)...")
    train_hash = {}
    for path, label in train:
        train_hash.setdefault(pixel_hash(path), set()).add(label)
    test_hashes = [pixel_hash(path) for path, _ in test]
    in_train = np.array([h in train_hash for h in test_hashes])
    same_label = np.array([h in train_hash and lab in train_hash[h] for h, (_, lab) in zip(test_hashes, test)])
    audit = {
        "class_counts": counts,
        "test_images_with_identical_pixels_in_train": int(in_train.sum()),
        "of_which_same_label_in_train": int(same_label.sum()),
        "duplicate_images_within_test": int(len(test_hashes) - len(set(test_hashes))),
    }
    print(json.dumps(audit, indent=1))

    # ---- Score the test set with the trained model ---------------------------------------
    model = load_face_model(args.model)
    X = np.stack([load_image(pth) for pth, _ in test])
    y = np.array([lab for _, lab in test])
    probs = model.predict(X, batch_size=64, verbose=0)
    pred = probs.argmax(axis=1)

    def report(mask):
        r = multiclass_metrics(y[mask], pred[mask])
        r["ci95"] = multiclass_bootstrap(y[mask], pred[mask])
        r["top_label_ece"] = top_label_ece(y[mask], probs[mask])
        return r

    res = {"model_file": Path(args.model).name, "audit": audit, "weights_check": getattr(model, "weights_check", None),
           "official_test": report(np.ones(len(y), bool)),
           "test_without_train_duplicates": report(~in_train)}
    (out / "face_fer2013.json").write_text(json.dumps(res, indent=2), encoding="utf-8")

    md = ["# Face emotion model (EfficientNetB0) - FER-2013 official test split", "",
          "Generated by `scripts/eval_face.py`. 7 emotions; 95 % bootstrap CIs (1000 resamples).", "",
          "## Split audit",
          f"- Test images whose exact pixels also appear in train: {audit['test_images_with_identical_pixels_in_train']} "
          f"(same label in train: {audit['of_which_same_label_in_train']})",
          f"- Duplicate images inside the test split: {audit['duplicate_images_within_test']}",
          f"- Test class counts: {counts['test']}", "", "## Results", ""]
    md += markdown_table({"official test": res["official_test"],
                          "test without train duplicates": res["test_without_train_duplicates"]})
    md += ["", f"Top-label ECE (official test): {res['official_test']['top_label_ece']:.3f}", "",
           "## Per class (official test)", ""] + per_class_table(res["official_test"])
    md += ["", "Confusion matrix (rows = true, columns = predicted, order: " + ", ".join(EMOTIONS) + "):", "```"]
    md += [" ".join(f"{v:5d}" for v in row) for row in res["official_test"]["confusion"]] + ["```"]
    text = "\n".join(md) + "\n"
    (out / "FACE_FER2013.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
