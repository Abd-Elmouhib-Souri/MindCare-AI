"""
CORE 2.5 (b) - TF-IDF + logistic regression baseline, evaluated with mindcare/metrics.py.

Protocol (fixed in advance):
  - fit on TRAIN only (vocabulary + weights)
  - choose the threshold on VALIDATION with the pre-registered rule (recall_1 >= 0.90)
  - report VALIDATION and the CHALLENGE SET (eval/challenge/challenge_v1.csv)
  - the TEST split is NOT used here: it is scored once, at the end, for all models together

Writes: eval/results/tfidf_logreg.json and eval/results/TFIDF_LOGREG.md

Usage (repo root, .venv active):
  python scripts/eval_tfidf_baseline.py --csv ..\\mindcare_data\\dataset\\text\\Suicide_Detection.csv
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))   # make "mindcare" importable
from mindcare.data import load_clean_dataset  # noqa: E402
from mindcare.tfidf import fit_tfidf_logreg  # noqa: E402
from mindcare.metrics import TARGET_RECALL, choose_threshold, evaluate, wilson_interval  # noqa: E402

CHALLENGE = Path("eval/challenge/challenge_v1.csv")


def fmt(m: dict, key: str) -> str:
    """'0.941 [0.938, 0.944]' : point estimate with its 95 % bootstrap interval."""
    lo, hi = m.get("ci95", {}).get(key, [None, None])
    return f"{m[key]:.3f}" + (f" [{lo:.3f}, {hi:.3f}]" if lo is not None else "")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--csv", required=True)
    p.add_argument("--out", default="eval/results")
    args = p.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    df = load_clean_dataset(args.csv)
    tr, va = df[df.split == "train"], df[df.split == "val"]          # test is not touched

    # Same configuration as probe P4: word 1-2 grams, NO stopword removal (keeps negations)
    print("Fitting TF-IDF + logistic regression on TRAIN...")
    predict = fit_tfidf_logreg(tr.text, tr.y)                         # shared definition: mindcare/tfidf.py

    val_score = predict(va.text)
    thr = choose_threshold(va.y.to_numpy(), val_score)                # pre-registered rule
    print(f"Threshold chosen on validation (recall_1 >= {TARGET_RECALL}): {thr:.4f}")
    print("Bootstrapping 95 % intervals (1000 resamples, about 1 minute)...")
    res = {
        "model": "tfidf_1-2gram_logreg",
        "target_recall": TARGET_RECALL,
        "threshold": thr,
        "val_at_0.5": evaluate(va.y, val_score, 0.5),
        "val_at_chosen": evaluate(va.y, val_score, thr),
    }

    # Challenge set: per-group accuracy with Wilson intervals (only 20 items per group)
    ch = pd.read_csv(CHALLENGE)
    ch["score"] = predict(ch.text)
    ch["pred"] = (ch["score"] >= thr).astype(int)
    ch["correct"] = (ch["pred"] == ch["label"]).astype(int)
    groups = {}
    for (g, lab), sub in ch.groupby(["group", "label"]):
        k, n = int(sub.correct.sum()), len(sub)
        groups[f"{g} (label {lab})"] = {"correct": k, "n": n, "accuracy": k / n,
                                        "wilson95": wilson_interval(k, n),
                                        "mean_score": float(sub.score.mean())}
    res["challenge_overall"] = evaluate(ch.label, ch.score, thr, with_ci=False)
    res["challenge_groups"] = groups
    res["challenge_items"] = ch[["id", "label", "score", "pred"]].round(4).to_dict("records")
    (out / "tfidf_logreg.json").write_text(json.dumps(res, indent=2), encoding="utf-8")

    v5, vc = res["val_at_0.5"], res["val_at_chosen"]
    md = [
        "# TF-IDF + LR baseline (train -> validation, challenge set; test untouched)", "",
        "Generated by `scripts/eval_tfidf_baseline.py`. 95 % bootstrap CIs (1000 resamples).", "",
        "## Validation", "| metric | threshold 0.5 | chosen threshold |", "|---|---|---|",
        f"| threshold | 0.5 | {thr:.4f} |",
    ]
    for k in ("accuracy", "macro_f1", "precision_1", "recall_1", "roc_auc", "pr_auc"):
        md.append(f"| {k} | {fmt(v5, k)} | {fmt(vc, k)} |")
    md += [f"| brier | {v5['brier']:.4f} | (same) |",
           f"| ECE (10 bins) | {v5['calibration']['ece']:.4f} | (same) |",
           f"| confusion (tp, fp, fn, tn) | {tuple(v5['confusion'].values())} | {tuple(vc['confusion'].values())} |",
           "", f"## Challenge set v1 (threshold {thr:.4f})",
           "| group | correct / n | accuracy [Wilson 95 %] | mean score |", "|---|---|---|---|"]
    for g, s in groups.items():
        lo, hi = s["wilson95"]
        md.append(f"| {g} | {s['correct']}/{s['n']} | {s['accuracy']:.2f} [{lo:.2f}, {hi:.2f}] | {s['mean_score']:.3f} |")
    co = res["challenge_overall"]
    md.append(f"\nOverall challenge accuracy: {co['accuracy']:.3f}, macro-F1: {co['macro_f1']:.3f} (n = {co['n']})")
    (out / "TFIDF_LOGREG.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
